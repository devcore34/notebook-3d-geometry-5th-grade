export function generateRandomNotebookTask() {
  const isCube = Math.random() < 0.25;
  let L, W, H;
  if (isCube) {
    const s = 1 + Math.floor(Math.random() * 4); // 1..4
    L = s;
    W = s;
    H = s;
  } else {
    do {
      L = 1 + Math.floor(Math.random() * 5); // 1..5
      W = 1 + Math.floor(Math.random() * 4); // 1..4
      H = 1 + Math.floor(Math.random() * 4); // 1..4
    } while (L === W && W === H);
  }
  return {
    id: 'task-random',
    num: '🎲',
    section: 'tasks',
    level: 'random',
    levelLabel: 'Случайная',
    badge: '🎲 Случайная задача',
    shortLabel: 'Случайная задача',
    title: `Случайная задача: ${isCube ? 'куб' : 'кубоид'} (${L} × ${W} × ${H})`,
    L,
    W,
    H,
    isCube,
    palette: 'amber',
    hideAnswerByDefault: true,
    description: `Начертите в тетради в клетку ${isCube ? 'куб' : 'кубоид'} с заданными измерениями (масштаб: 1 ед. = 2 клетки).`,
    callout: `Перевод в клетки: 🔵 Длина → ${L * 2} кл., 🟠 Ширина ↗ ${pluralDiags(W)}, 🟢 Высота ↕ ${H * 2} кл.`,
    tip: `Сначала передняя грань (${L * 2} × ${H * 2} кл.), затем ${pluralDiags(W)} вправо-вверх от трёх углов, затем задние рёбра!`,
  };
}
