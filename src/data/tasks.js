// Масштаб тетради в клетку: 1 единица = 2 клетки!
// Длина (L) -> горизонтально вправо (1 ед. = 2 клетки)
// Высота (H) -> вертикально вверх/вниз (1 ед. = 2 клетки)
// Ширина / глубина (W) -> по диагонали клеток вправо-вверх (1 ед. = 1 диагональ клетки: +1 кл. вправо, +1 кл. вверх)

export const CELLS_PER_UNIT = 2;

export function pluralUnits(n) {
  const mod10 = n % 10;
  const mod100 = n % 100;
  if (mod10 === 1 && mod100 !== 11) return `${n} единица`;
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return `${n} единицы`;
  return `${n} единиц`;
}

export function pluralCells(n) {
  const mod10 = n % 10;
  const mod100 = n % 100;
  if (mod10 === 1 && mod100 !== 11) return `${n} клетка`;
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return `${n} клетки`;
  return `${n} клеток`;
}

export function pluralDiags(n) {
  const mod10 = n % 10;
  const mod100 = n % 100;
  if (mod10 === 1 && mod100 !== 11) return `${n} диагональ`;
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return `${n} диагонали`;
  return `${n} диагоналей`;
}

export function pluralCubes(n) {
  const mod10 = n % 10;
  const mod100 = n % 100;
  if (mod10 === 1 && mod100 !== 11) return `${n} кубическая единица`;
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return `${n} кубические единицы`;
  return `${n} кубических единиц`;
}

